inline int getPSTValue(Piece piece, Square square, Color color, bool endgame) {
    const int* pst = endgame ? PST_EG[piece] : PST_MG[piece];
    Square sq = (color == WHITE) ? square : Square(square ^ 56);
    return pst[sq];
}
